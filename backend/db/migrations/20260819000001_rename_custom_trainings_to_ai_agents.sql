- 对可逆决策加快评估，对不可逆决策放慢评估。如果决策是可逆的，偏好小实验而非无尽的分析。
- 重要决策需要备用计划和时机。如果存在已知的时间窗口，应在预期时间的大约三分之二处做出决定，而不是等到最后一刻。
- 偏好稳健的决策而非完美的决策。一个良好的决策，即使其中一项假设被证明是错的，也应该仍然可以接受。
