- 筛选模型：设计测试或过滤器，使不同类型的人自我揭示。用于选择合伙人、员工、供应商或机会。
- 委托代理模型：行动方可能与委托方的激励不一致。使用监督、对齐奖励、里程碑和明确问责。
- 道德风险：当人们不承担全部成本时，会冒更大风险。用于授权、类保险情境和团队问责。
