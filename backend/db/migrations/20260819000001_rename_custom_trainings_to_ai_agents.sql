- 建议过滤：谁受益 -> 证据质量 -> 经验匹配度 -> 偏差检查。在用户被他人建议淹没时使用。
- 真实需求测试：表面欲望 -> 真实需求 -> 短期舒适 vs 长期价值 -> 匹配度。在用户想要什么但不确定是否真正对自己好时使用。
