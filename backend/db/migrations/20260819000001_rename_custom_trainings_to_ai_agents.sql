- 当决策很重要时，至少询问三位背景不同的人，然后按激励、专业能力和风险承受能力过滤他们的建议。
- 当其他人的激励、反应、信任、竞争、合作、谈判或重复互动很重要时，将决策视为一场博弈，而非单人优化。
- 在策略情境下，询问：玩家是谁？每个玩家可以选什么？每个玩家想要什么？如果我选X，他们会怎么做？这是一次性的还是重复的？承诺、信任、信息或规则能否改变结果？
